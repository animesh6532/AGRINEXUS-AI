"""
Crop profiles database module.
Provides research-backed environmental requirements, optimal and acceptable ranges,
seasonal windows, soil preferences, and authoritative source metadata (FAO ECOCROP, ICAR).
"""

from typing import Dict, Any, List, Optional, Tuple
from pydantic import BaseModel, Field


class CropRequirementProfile(BaseModel):
    crop: str
    display_name: str
    scientific_name: str
    ml_supported: bool
    category: str  # cereal, pulse, cash_crop, fruit, oilseed, vegetable
    seasons: List[str]  # kharif, rabi, zaid, annual
    temp_optimal: Tuple[float, float]  # Celsius (min, max)
    temp_acceptable: Tuple[float, float]
    rainfall_optimal: Tuple[float, float]  # mm per season (min, max)
    rainfall_acceptable: Tuple[float, float]
    humidity_optimal: Tuple[float, float]  # % (min, max)
    ph_optimal: Tuple[float, float]  # pH (min, max)
    ph_acceptable: Tuple[float, float]
    soil_textures: List[str]  # e.g., ["clay", "clay loam", "loam"]
    drainage: str  # well-drained, moderate, flooded
    soil_depth_min_cm: int
    water_requirement: str  # high, medium, low
    growth_duration_days: Tuple[int, int]
    regional_suitability: List[str]  # List of Indian states/regions or ["all"]
    source: str
    source_url: str
    notes: str


