def get_crop_profile(crop_name: str) -> Optional[CropRequirementProfile]:
    """Retrieve crop requirement profile by key or display name (case-insensitive)."""
    key = crop_name.strip().lower()
    if key in CROP_PROFILES:
        return CROP_PROFILES[key]
    for profile in CROP_PROFILES.values():
        if profile.display_name.lower() == key or profile.scientific_name.lower() == key:
            return profile
    return None


def get_all_crop_profiles() -> List[CropRequirementProfile]:
    """Return all supported crop profiles in the agricultural catalogue."""
    return list(CROP_PROFILES.values())
